export interface Fingering {
  id: string;
  octaveModifier: number;
  keys: number[];
}

export function fingeringsFor(midi: number): Fingering[] {
  const note = midiToNoteName(midi);
  const fingerings = simpleNoteToFingers[note.replace(/\d+/, '')];

  if (!fingerings) {
    throw `No fingering for note ${note}`;
  }

  return fingerings.map(([octaveModifier, keys], i) => ({
    id: `${note}_${i}`,
    octaveModifier,
    keys,
  }));
}

// the first fingering is the default when none was chosen
export function preferredFingering(
  midi: number,
  preferredId: string | null,
): Fingering {
  const fingerings = fingeringsFor(midi);
  return fingerings.find(f => f.id === preferredId) ?? fingerings[0];
}

export function octaveRoller(midi: number, fingering: Fingering): number {
  return noteOctave(midi) + fingering.octaveModifier;
}

// key indexes, in the order used by `simpleNoteToFingers`
const keyLabels = [
  'left 1',
  'the bis key',
  'left 2',
  'left 3',
  'left pinky 1',
  'left pinky 2',
  'the right side key',
  'right 1',
  'right 2',
  'right 3',
  'right pinky 1',
  'right pinky 2',
  'right pinky 3',
];

const pressed = (keys: number[], indexes: number[]) =>
  indexes.filter(i => keys[i] === 1);

const joinAnd = (parts: string[]): string =>
  parts.length <= 1
    ? parts.join('')
    : parts.slice(0, -1).join(', ') + ' and ' + parts[parts.length - 1];

const capitalise = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

// e.g. "Left 1 · 2 · 3 and right 2, octave roller 4"
export function describeFingering(midi: number, fingering: Fingering): string {
  const { keys } = fingering;
  const fingers = (hand: string, indexes: number[]) => {
    const numbers = pressed(keys, indexes).map(i => indexes.indexOf(i) + 1);
    return numbers.length > 0 ? [`${hand} ${numbers.join(' · ')}`] : [];
  };

  const parts = [
    ...fingers('left', [0, 2, 3]),
    ...pressed(keys, [1, 4, 5, 6]).map(i => keyLabels[i]),
    ...fingers('right', [7, 8, 9]),
    ...pressed(keys, [10, 11, 12]).map(i => keyLabels[i]),
  ];

  const description = parts.length > 0 ? joinAnd(parts) : 'no keys';
  return capitalise(
    `${description}, octave roller ${octaveRoller(midi, fingering)}`,
  );
}

// e.g. "a semitone high"
export function describeInterval(expected: number, played: number): string {
  const distance = Math.abs(played - expected);
  const size = distance === 1
    ? 'a semitone'
    : distance === 2
    ? 'a whole tone'
    : distance === 12
    ? 'an octave'
    : `${distance} semitones`;
  return `${size} ${played > expected ? 'high' : 'low'}`;
}

// Compares the expected fingering with the closest fingering of the note that
// was played, e.g. "Press right 2 as well to drop to F♯4."
export function fingeringHint(
  expected: number,
  fingering: Fingering,
  played: number,
): string | null {
  const allKeys = fingering.keys.map((_, i) => i);
  const roller = octaveRoller(expected, fingering);

  const difference = (f: Fingering) => ({
    toPress: allKeys.filter(i => fingering.keys[i] === 1 && f.keys[i] === 0),
    toLift: allKeys.filter(i => fingering.keys[i] === 0 && f.keys[i] === 1),
    rollerDelta: roller - octaveRoller(played, f),
  });
  const size = (d: ReturnType<typeof difference>) =>
    d.toPress.length + d.toLift.length + (d.rollerDelta === 0 ? 0 : 1);

  const closest = fingeringsFor(played)
    .map(difference)
    .reduce((best, d) => size(d) < size(best) ? d : best);

  if (size(closest) === 0 || size(closest) > 3) {
    return null;
  }

  const actions = [
    ...(closest.toPress.length > 0
      ? [
        `press ${joinAnd(closest.toPress.map(i => keyLabels[i]))}`
        + (closest.toLift.length === 0 ? ' as well' : ''),
      ]
      : []),
    ...(closest.toLift.length > 0
      ? [`lift ${joinAnd(closest.toLift.map(i => keyLabels[i]))}`]
      : []),
    ...(closest.rollerDelta !== 0
      ? [
        `roll ${closest.rollerDelta > 0 ? 'up' : 'down'} to octave roller `
        + roller,
      ]
      : []),
  ];

  const direction = played > expected ? 'drop to' : 'go up to';
  return capitalise(
    `${joinAnd(actions)} to ${direction} ${displayNoteName(expected)}.`,
  );
}

